import {
  changedFields,
  type ImportCandidate,
  type ImportField,
} from '../domain/importCandidate.ts';
import { checkPinyin } from '../domain/pinyin.ts';
import { containsHan, normalizeTags, normalizeText } from '../domain/validation.ts';
import type { Word } from '../domain/word.ts';
import type { PinyinTool } from './enrich/pinyinTool.ts';
import type { RawEntry } from './types.ts';

/**
 * - `new` / `restore`: will be added (`restore` brings back a soft-deleted word, same id).
 * - `duplicate`: already in the deck with the same data, or repeated earlier in the file: skipped.
 * - `changed`: already in the deck but the file brings different pinyin/meaning/tags:
 *   skipped unless the user opts in to updating changed words.
 * - `error`: cannot be imported.
 * Warnings are orthogonal: a `new` row can carry warnings and is still imported.
 */
export type RowStatus = 'new' | 'restore' | 'duplicate' | 'changed' | 'error';

export type RowError =
  | { readonly kind: 'missing-hanzi' }
  | { readonly kind: 'no-han'; readonly hanzi: string }
  | { readonly kind: 'extra-cells'; readonly count: number };

export type RowWarning =
  | { readonly kind: 'pinyin-mismatch'; readonly suggested: string }
  | { readonly kind: 'pinyin-no-tones'; readonly suggested: string }
  | { readonly kind: 'non-han'; readonly chars: readonly string[] };

export interface PreviewRow {
  readonly entry: RawEntry;
  readonly status: RowStatus;
  readonly errors: readonly RowError[];
  readonly warnings: readonly RowWarning[];
  /** What would be written. Absent for errors and in-file duplicates. */
  readonly candidate?: ImportCandidate;
  /** Pinyin was missing in the file and generated by pinyin-pro (shown as "generated"). */
  readonly pinyinGenerated: boolean;
  /** For `changed` rows. */
  readonly changedFields?: readonly ImportField[];
  /** For in-file duplicates: line of the first occurrence. */
  readonly duplicateOfLine?: number;
  /** For `duplicate`/`changed` rows matching a saved word. */
  readonly existingWordId?: string;
}

export interface PreviewSummary {
  readonly total: number;
  readonly byStatus: Readonly<Record<RowStatus, number>>;
  /** Rows (of any status except error) with at least one warning. */
  readonly withWarnings: number;
}

export interface Preview {
  readonly rows: readonly PreviewRow[];
  readonly summary: PreviewSummary;
}

export interface PreviewContext {
  /** Non-deleted words of the target deck (empty for a new deck). */
  readonly existing: readonly Word[];
  /** Normalized hanzi of soft-deleted words in the target deck. */
  readonly deletedHanzi: ReadonlySet<string>;
  readonly pinyin: PinyinTool;
}

function rowErrors(entry: RawEntry, hanzi: string): RowError[] {
  const errors: RowError[] = [];
  if (hanzi === '') errors.push({ kind: 'missing-hanzi' });
  else if (!containsHan(hanzi)) errors.push({ kind: 'no-han', hanzi });
  if (entry.extraCells !== undefined) errors.push({ kind: 'extra-cells', count: entry.extraCells });
  return errors;
}

function nonHanChars(hanzi: string): string[] {
  return [...new Set(hanzi.match(/[^\p{Script=Han}\s]/gu) ?? [])];
}

function enrich(entry: RawEntry, hanzi: string, tool: PinyinTool) {
  const warnings: RowWarning[] = [];
  const nonHan = nonHanChars(hanzi);
  if (nonHan.length > 0) warnings.push({ kind: 'non-han', chars: nonHan });

  const pinyinGenerated = entry.pinyin === undefined;
  const pinyin = entry.pinyin ?? tool.suggest(hanzi);
  if (!pinyinGenerated) {
    const check = checkPinyin(pinyin, tool.readings(hanzi));
    // Never overwrite: keep the file's pinyin and show the suggestion next to it.
    if (check === 'mismatch')
      warnings.push({ kind: 'pinyin-mismatch', suggested: tool.suggest(hanzi) });
    if (check === 'no-tones')
      warnings.push({ kind: 'pinyin-no-tones', suggested: tool.suggest(hanzi) });
  }

  const candidate: ImportCandidate = {
    hanzi,
    pinyin,
    meaning: entry.meaning ?? '',
    tags: normalizeTags(entry.tags ?? []),
    provided: {
      pinyin: !pinyinGenerated,
      meaning: entry.meaning !== undefined,
      tags: entry.tags !== undefined,
    },
  };
  return { candidate, warnings, pinyinGenerated };
}

function classify(
  entry: RawEntry,
  ctx: PreviewContext,
  firstLineByHanzi: Map<string, number>,
): PreviewRow {
  const hanzi = normalizeText(entry.hanzi);
  const errors = rowErrors(entry, hanzi);
  if (errors.length > 0) {
    return { entry, status: 'error', errors, warnings: [], pinyinGenerated: false };
  }

  const { candidate, warnings, pinyinGenerated } = enrich(entry, hanzi, ctx.pinyin);
  const base = { entry, errors, warnings, pinyinGenerated };

  const firstLine = firstLineByHanzi.get(hanzi);
  if (firstLine !== undefined) return { ...base, status: 'duplicate', duplicateOfLine: firstLine };
  firstLineByHanzi.set(hanzi, entry.line);

  const existing = ctx.existing.find((w) => w.hanzi === hanzi);
  if (existing) {
    const fields = changedFields(existing, candidate);
    return fields.length > 0
      ? {
          ...base,
          status: 'changed',
          candidate,
          changedFields: fields,
          existingWordId: existing.id,
        }
      : { ...base, status: 'duplicate', candidate, existingWordId: existing.id };
  }
  const status = ctx.deletedHanzi.has(hanzi) ? 'restore' : 'new';
  return { ...base, status, candidate };
}

/** Pure: classifies every parsed row against the file itself and the target deck. */
export function buildPreview(entries: readonly RawEntry[], ctx: PreviewContext): Preview {
  const firstLineByHanzi = new Map<string, number>();
  const rows = entries.map((entry) => classify(entry, ctx, firstLineByHanzi));

  const byStatus: Record<RowStatus, number> = {
    new: 0,
    restore: 0,
    duplicate: 0,
    changed: 0,
    error: 0,
  };
  for (const row of rows) byStatus[row.status]++;
  const withWarnings = rows.filter((r) => r.status !== 'error' && r.warnings.length > 0).length;

  return { rows, summary: { total: rows.length, byStatus, withWarnings } };
}

/**
 * Candidates to commit: new and restored rows, plus changed rows when `updateChanged` is set.
 * Duplicates (same data) are left out; the commit re-checks against the database anyway.
 */
export function candidatesToCommit(
  preview: Preview,
  options: { updateChanged: boolean },
): ImportCandidate[] {
  return preview.rows.flatMap((row) => {
    const wanted =
      row.status === 'new' ||
      row.status === 'restore' ||
      (row.status === 'changed' && options.updateChanged);
    return wanted && row.candidate ? [row.candidate] : [];
  });
}
